extern crate creusot_std;

use creusot_std::prelude::*;

pub trait T {
    #[ensures((^x)@ == 0)]
    fn m(&self, x: &mut u32);
}

pub struct S;

impl T for S {
    #[doc = "__trust_wp_spec_tc"]
    fn m(&self, x: &mut u32) {
        *x = 1;
    }
}

#[ensures(result@ == 0)]
