use super::{CallSiteContext, *};

pub(super) fn handle_direct_spec_call<'tcx>(
    call_site: CallSiteContext<'_, 'tcx>,
    func: &Operand<'tcx>,
    session: &mut ExtractionSession<'_>,
    def_id: DefId,
    spec: &StdSpec,
    effects: &mut CallEffects,
) -> Option<PureExpr> {
    let CallSiteContext {
        tcx,
        body,
        args,
        destination,
        next_bb,
        mut local_exprs,
        visited,
        ctx,
        projected_write_facts,
    } = call_site;
    // Per-borrow prophecy carriers (#124), Phase A — BEFORE argument
    // translation: a mutating `&mut` argument whose tracked value is a ground
    // constant (the locally-rooted-borrow shape behind the closed
    // `^<constant>` false accept) is rebound to a freshly minted MutRef
    // carrier keyed on the borrow LOCAL, so the callee's contract
    // instantiates `^arg`/`*arg` against a real prophecy variable instead of
    // a literal. The callee-entry binding `*carrier == <value>` lands in the
    // same assumption channel as the callee's ensures.
    let mint_param_names = resolve_arg_names_or_warn(tcx, def_id, spec.param_names.as_ref());
    let mint_positions = spec_mutating_ref_arg_positions(
        body,
        args,
        spec,
        (!mint_param_names.is_empty()).then_some(mint_param_names.as_slice()),
    );
    let pending_advancement = super::super::borrow_carriers::mint_carriers_for_call_args(
        tcx,
        body,
        ctx.arg_names,
        args,
        &mint_positions,
        &mut local_exprs,
        &mut session.effects.assumptions,
    );
    // Per-borrow prophecy carriers, closure-capture lane
    // (#closure-capture-carriers), Phase A — BEFORE argument translation: a
    // state-mutating call consuming a closure whose by-`&mut` captures track
    // ground constants gets those environment fields rebound to freshly
    // minted MutRef carriers keyed on the capture borrow locals, so the
    // closure's contract (and every capture post-state projection) reads a
    // real prophecy variable instead of `^<constant>`. The callee-entry
    // binding `*carrier == <value>` lands in the same assumption channel.
    let closure_state_mutating =
        call_mutates_closure_state(tcx, func) || spec_mutates_closure_state(spec);
    let mut closure_pending_advancements = Vec::new();
    if closure_state_mutating {
        for arg in args {
            let (Operand::Move(place) | Operand::Copy(place)) = &arg.node else {
                continue;
            };
            if !place.projection.is_empty()
                || !matches!(
                    body.local_decls[place.local].ty.kind(),
                    rustc_middle::ty::TyKind::Closure(..)
                )
            {
                continue;
            }
            let closure_pending = super::super::borrow_carriers::mint_carriers_for_closure_captures(
                tcx,
                body,
                ctx.arg_names,
                place.local,
                &mut local_exprs,
                &mut session.effects.assumptions,
            );
            if !closure_pending.is_empty() {
                closure_pending_advancements.push(closure_pending);
            }
        }
    }
    let mut translated_args =
        translate_call_args_for_substitutions_with_tcx(args, &local_exprs, Some(body), Some(tcx));
    let result_var = call_result_symbol(body, destination.local, tcx);
    let mut param_names = resolve_arg_names_or_warn(tcx, def_id, spec.param_names.as_ref());
    extend_call_with_const_generic_args(tcx, def_id, func, &mut translated_args, &mut param_names);
    let param_names = (!param_names.is_empty()).then_some(param_names.as_slice());

    // Snapshot the effect-vector lengths so the open-logic unfolding pass below
    // can target ONLY the obligations/assumptions generated by THIS call. (#mutex)
    let obligations_before = session.effects.obligations.len();
    let assumptions_before = session.effects.assumptions.len();

    // Excl-gated `valid_op_lemma` exclusivity fact (#2315). When the callee is
    // `valid_op_lemma` on a `Resource<Excl<_>>` receiver, the committed
    // `requires: self.id() == other.id()` becomes a caller obligation that
    // contradicts excl.rs's own `id != id` postcondition. For Excl the precond
    // is unconditionally satisfiable-free (distinct &mut/& resources never share
    // an id), so we emit NO caller obligation here — see
    // `excl_valid_op_lemma_clear_requires` for the soundness argument.
    if !excl_valid_op_lemma_clear_requires(tcx, func, def_id) {
        apply_preconditions_with_effects(
            &spec.requires,
            &translated_args,
            param_names,
            &mut *session.effects,
        );
    }
    // Excl-gated `valid_op_lemma` exclusivity fact (#2315). When the callee is
    // `valid_op_lemma` on a `Resource<Excl<_>>` receiver, append the sound,
    // op-free consequence `self.id() != other.id()` so the lemma's intended
    // effect reaches the VC (the `op != None` ensures is unencodable because
    // `Excl` is erased before the encoder). Strictly gated to Excl receivers —
    // see `excl_valid_op_lemma_ensures` for the soundness argument.
    let augmented_ensures = excl_valid_op_lemma_ensures(tcx, func, def_id, &spec.ensures);
    // Ag-gated `join_shared` view-agreement fact (#quantifier-frontier). The
    // committed spec withholds Creusot's unrenderable `incl_eq` conjunct; for a
    // `Resource<Ag<_>>` receiver that conjunct COLLAPSES to `self@ == other@`,
    // which is a theorem of the contract at `Ag` and unsound at any RA with
    // non-trivial inclusion. See `ag_join_shared_ensures` for the derivation.
    let ensures: &[String] = augmented_ensures.as_deref().unwrap_or(&spec.ensures);
    let ag_ensures = ag_join_shared_ensures(tcx, func, def_id, ensures);
    let ensures: &[String] = ag_ensures.as_deref().unwrap_or(ensures);
    let result_expr = apply_postconditions_with_effects(
        ensures,
        &result_var,
        &translated_args,
        param_names,
        &mut *session.effects,
        true,
    );
    let result_expr = if preserves_empty_seq_constructor_carrier(&result_expr) {
        result_var.clone()
    } else {
        result_expr
    };

    // Monomorphization-aware unfolding of OPEN trait-logic methods (e.g.
    // `<Even as Inv<u32>>::inv`) in the obligations/assumptions this call just
    // generated. Sound, gated, and a no-op unless an unambiguous open resolution
    // exists for the callee's substs. See `open_logic_unfold`. (#mutex)
    super::open_logic_unfold::unfold_open_logic_in_effects(
        tcx,
        func,
        session.effects,
        obligations_before,
        assumptions_before,
    );

    // `snapshot!(*a)` for `a: &mut T` lowers to a shared reborrow chain
    // `_t = &(*a); _u = &(*_t); capture(_u)`. Reborrow cancellation in the
    // rvalue translator collapses the chain to the bare mut-ref identity
    // `Var("a", MutRef(_))`, so `Snapshot::capture`'s `result == value`
    // postcondition binds the snapshot to the REFERENCE instead of freezing
    // the current dereferenced value at the capture point. Because `a`'s
    // own substitution is later advanced to its prophecy/final after an
    // intervening `&mut` call, `*a_p` then incorrectly follows `^a`. When
    // the capture target `T` is a non-reference value (so the snapshot
    // stores a value, not a borrow) but the bound result is a `MutRef`-sorted
    // var, a deref layer was over-cancelled: recover the current pointee. (#682)
    let result_expr =
        recover_snapshot_capture_current_pointee(tcx, body, def_id, args, result_expr);

    let pre_call_self = translated_args.first().map(|arg| arg.expr.clone());
    let first_arg_mut_ref = first_call_arg_is_mut_ref(body, args);
    let mutating_ref_positions = spec_mutating_ref_arg_positions(body, args, spec, param_names);
    propagate_mutating_ref_arg_states_for_positions(
        &mut local_exprs,
        body,
        ctx.arg_names,
        args,
        &mutating_ref_positions,
        Some(effects),
        None,
    );
    // Per-borrow prophecy carriers (#124), Phase B — AFTER the shared
    // receiver-state propagation (which now sees the carrier, not the raw
    // constant, so its equality rewrite can no longer conflate every
    // coincidentally-equal local): advance each base local in the consumed
    // borrow's chain to `Final(<carrier of the local that borrows it>)` and
    // arm the expiry resolution of the non-consumed chain borrows.
    if !pending_advancement.is_empty() {
        super::super::borrow_carriers::apply_chain_advancement(
            tcx,
            body,
            ctx.arg_names,
            &pending_advancement,
            &mut local_exprs,
        );
    }
    if !first_arg_mut_ref && closure_state_mutating {
        effects.has_mutating_call_effect = true;
        if let Some(self_expr) = pre_call_self.as_ref() {
            propagate_mutating_receiver_state_with_captures(
                &mut local_exprs,
                body,
                ctx.arg_names,
                self_expr,
                None,
            );
        }
    }
    // Closure-capture lane (#closure-capture-carriers), Phase B — AFTER the
    // capture-state propagation (which now sees the carrier environment):
    // advance each capture borrow's chain root to `Final(<carrier>)` and
    // re-arm the expiry of the non-consumed chain ancestors. The consumed
    // capture borrow itself gets no caller-side expiry fact (RustHorn).
    for closure_pending in &closure_pending_advancements {
        super::super::borrow_carriers::apply_chain_advancement(
            tcx,
            body,
            ctx.arg_names,
            closure_pending,
            &mut local_exprs,
        );
    }
    local_exprs.insert(destination.local, result_expr);
    wrap_call_context(
        wrap_projected_facts(
            projected_write_facts.to_vec(),
            super::extract_from_block_with_context(
                tcx,
                body,
                next_bb,
                local_exprs,
                visited,
                ctx,
                effects,
            ),
        ),
        ctx.scope_call_context,
        &mut *session.effects,
    )
}

pub(super) fn handle_extern_spec_call<'tcx>(
    call_site: CallSiteContext<'_, 'tcx>,
    func: &Operand<'tcx>,
    session: &mut ExtractionSession<'_>,
    def_id: DefId,
    spec: &StdSpec,
    effects: &mut CallEffects,
) -> Option<PureExpr> {
    let CallSiteContext {
        tcx,
        body,
        args,
        destination,
        next_bb,
        mut local_exprs,
        visited,
        ctx,
        projected_write_facts,
    } = call_site;
    let (mut effective_spec, effective_args, effective_param_names, effective_self_expr) =
        resolve_effective_spec(tcx, body, func, args, &local_exprs, ctx, def_id, spec);
    specialize_default_postconditions_for_call(tcx, body, args, def_id, &mut effective_spec);

    // Excl-gated `valid_op_lemma` exclusivity fact (#2315). When the callee is
    // `valid_op_lemma` on a `Resource<Excl<_>>` receiver, append the sound,
    // op-free consequence `self.id() != other.id()` so the lemma's intended
    // effect reaches the VC. The committed `op != None` ensures is unencodable
    // (the encoder has no `op` method — `Excl` is erased before encoding), so
    // without this the lemma is inert. Strictly gated to Excl receivers — see
    // `excl_valid_op_lemma_ensures` for the soundness argument.
    // Filter the EFFECTIVE ensures (post specialize_default_postconditions_for_call),
    // not the original spec.ensures, so any prior specialization is preserved.
    if let Some(augmented) = excl_valid_op_lemma_ensures(tcx, func, def_id, &effective_spec.ensures)
    {
        effective_spec.ensures = augmented;
    }
    // Excl-gated `valid_op_lemma`: drop the committed `requires: id == other.id`.
    // It would otherwise be emitted as a caller obligation here that contradicts
    // excl.rs's `id != id` postcondition (the *real* blocker). For Excl the
    // precondition holds unconditionally — distinct &mut/& Excl resources never
    // share an id — so no obligation is owed. Same gate as the ensures rewrite,
    // so it can never partially apply. See `excl_valid_op_lemma_clear_requires`.
    if excl_valid_op_lemma_clear_requires(tcx, func, def_id) {
        effective_spec.requires.clear();
    }
    // Ag-gated `join_shared` view-agreement fact (#quantifier-frontier). Same
    // shape as the Excl rewrite above and filtered on the EFFECTIVE ensures for
    // the same reason. See `ag_join_shared_ensures` for the derivation of why
    // `self@ == other@` is a theorem of Creusot's contract at `Ag` and unsound
    // at any RA with non-trivial inclusion.
    if let Some(augmented) = ag_join_shared_ensures(tcx, func, def_id, &effective_spec.ensures) {
        effective_spec.ensures = augmented;
    }
    let result_var = call_result_symbol(body, destination.local, tcx);
    // Snapshot effect-vector lengths for the open-logic unfolding pass below, so
    // it rewrites only THIS call's freshly generated clauses. (#mutex)
    let unfold_obligations_before = session.effects.obligations.len();
    let unfold_assumptions_before = session.effects.assumptions.len();
    apply_preconditions_with_self_and_effects(
        &effective_spec.requires,
        &effective_args,
        effective_param_names.as_deref(),
        effective_self_expr.as_ref(),
        &mut *session.effects,
    );

    let assumptions_before = session.effects.assumptions.len();
    let mut result_expr = apply_postconditions_with_self_and_effects(
        &effective_spec.ensures,
        &result_var,
        &effective_args,
        effective_param_names.as_deref(),
        effective_self_expr.as_ref(),
        &mut *session.effects,
    );
    if preserves_empty_seq_constructor_carrier(&result_expr) {
        result_expr = result_var.clone();
    }

    // Monomorphization-aware unfolding of OPEN trait-logic methods in the
    // obligations/assumptions this call generated, before any later assumption
    // rewriting (closure-capture substitution) composes over them. (#mutex)
    super::open_logic_unfold::unfold_open_logic_in_effects(
        tcx,
        func,
        session.effects,
        unfold_obligations_before,
        unfold_assumptions_before,
    );

    if let Some(self_expr) = effective_self_expr.as_ref() {
        let capture_bindings = closure_capture_bindings(self_expr);
        if !capture_bindings.is_empty() {
            result_expr = substitute_capture_fields_in_postcondition(
                &result_expr,
                &capture_bindings,
                self_expr,
                false,
            );
            for assumption in session
                .effects
                .assumptions
                .iter_mut()
                .skip(assumptions_before)
            {
                *assumption = substitute_capture_fields_in_postcondition(
                    assumption,
                    &capture_bindings,
                    self_expr,
                    false,
                );
            }
        }
    }

    let pre_call_self = effective_self_expr
        .clone()
        .or_else(|| effective_args.first().map(|arg| arg.expr.clone()));
    let first_arg_mut_ref = first_call_arg_is_mut_ref(body, args);
    let uses_concrete_closure_user_spec = extract_closure_def_id_from_fn_call(func)
        .is_some_and(|closure_def_id| ctx.user_specs.contains_key(&closure_def_id));
    let mutating_ref_positions = if uses_concrete_closure_user_spec {
        if first_arg_mut_ref && spec_mutates_closure_state(&effective_spec) {
            vec![0]
        } else {
            Vec::new()
        }
    } else {
        spec_mutating_ref_arg_positions(
            body,
            args,
            &effective_spec,
            effective_param_names.as_deref(),
        )
    };
    propagate_mutating_ref_arg_states_for_positions(
        &mut local_exprs,
        body,
        ctx.arg_names,
        args,
        &mutating_ref_positions,
        Some(effects),
        None,
    );
    if !first_arg_mut_ref
        && (call_mutates_closure_state(tcx, func) || spec_mutates_closure_state(&effective_spec))
    {
        effects.has_mutating_call_effect = true;
        if let Some(self_expr) = pre_call_self.as_ref() {
            propagate_mutating_receiver_state_with_captures(
                &mut local_exprs,
                body,
                ctx.arg_names,
                self_expr,
                None,
            );
        }
    }
    // `snapshot!(*a)` of a `&mut T` deref is resolved via the extern
    // `Snapshot::capture` spec. Freeze the current pointee value rather than
    // aliasing the mut-ref identity (which later follows the prophecy/final).
    // See `recover_snapshot_capture_current_pointee`. (#682)
    let result_expr =
        recover_snapshot_capture_current_pointee(tcx, body, def_id, args, result_expr);
    local_exprs.insert(destination.local, result_expr);
    wrap_call_context(
        wrap_projected_facts(
            projected_write_facts.to_vec(),
            super::extract_from_block_with_context(
                tcx,
                body,
                next_bb,
                local_exprs,
                visited,
                ctx,
                effects,
            ),
        ),
        ctx.scope_call_context,
        &mut *session.effects,
    )
}

/// Resolve the effective spec, args, param names, and self expr for a call.
///
/// Handles closure-aware resolution: when the call target is a concrete closure
/// with user-annotated contracts, uses the closure's spec instead of the generic
/// Fn trait spec.
#[allow(clippy::type_complexity)]
#[allow(clippy::too_many_arguments)]
fn resolve_effective_spec<'tcx>(
    tcx: TyCtxt<'tcx>,
    body: &Body<'tcx>,
    func: &Operand<'tcx>,
    args: &[Spanned<Operand<'tcx>>],
    local_exprs: &HashMap<Local, PureExpr>,
    ctx: &BlockExtractionContext<'_>,
    def_id: DefId,
    spec: &StdSpec,
) -> (
    StdSpec,
    Vec<TranslatedArg>,
    Option<Vec<String>>,
    Option<PureExpr>,
) {
    if let Some(closure_def_id) = extract_closure_def_id_from_fn_call(func) {
        if let Some(closure_spec) = ctx.user_specs.get(&closure_def_id) {
            let closure_args = translate_call_args_for_substitutions_with_tcx(
                &args[1..],
                local_exprs,
                Some(body),
                Some(tcx),
            );
            let closure_param_names = arg_names_for_def_id(tcx, closure_def_id);
            let closure_self_expr = args
                .first()
                .and_then(|arg| translate_operand(&arg.node, local_exprs));
            return (
                closure_spec.clone(),
                closure_args,
                closure_param_names,
                closure_self_expr,
            );
        }
        let translated_args = translate_call_args_for_substitutions_with_tcx(
            args,
            local_exprs,
            Some(body),
            Some(tcx),
        );
        let param_names = resolve_spec_or_mir_arg_names(tcx, def_id, spec.param_names.as_ref());
        let self_expr = normalize_extern_spec_self_expr(
            &tcx.def_path_str(def_id),
            derive_self_expr_from_args(&translated_args),
        );
        return (spec.clone(), translated_args, param_names, self_expr);
    }
    if let Some(fn_def_id) = extract_fn_item_def_id_from_fn_trait_call(func) {
        if let Some(fn_spec) = ctx.user_specs.get(&fn_def_id) {
            let fn_args = translate_call_args_for_substitutions_with_tcx(
                &args[1.min(args.len())..],
                local_exprs,
                Some(body),
                Some(tcx),
            );
            let fn_param_names = arg_names_for_def_id(tcx, fn_def_id);
            return (fn_spec.clone(), fn_args, fn_param_names, None);
        }
    }
    let translated_args =
        translate_call_args_for_substitutions_with_tcx(args, local_exprs, Some(body), Some(tcx));
    let param_names = resolve_spec_or_mir_arg_names(tcx, def_id, spec.param_names.as_ref());
    let self_expr = normalize_extern_spec_self_expr(
        &tcx.def_path_str(def_id),
        derive_self_expr_from_args(&translated_args),
    );
    (spec.clone(), translated_args, param_names, self_expr)
}

fn preserves_empty_seq_constructor_carrier(expr: &PureExpr) -> bool {
    matches!(
        expr,
        PureExpr::LogicFnCall { name, args }
            if args.is_empty() && matches!(name.as_str(), "seq_empty" | "Seq::empty")
    )
}
